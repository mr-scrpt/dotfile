#!/usr/bin/env bash
# Обёртка для условных waybar-индикаторов (return-type: json).
# Добавляет разделитель " |" перед текстом, только когда индикатор видим
# (text непустой). Waybar прячет модуль лишь при пустом итоге форматирования,
# поэтому разделитель в "format" висел бы постоянно — а здесь он живёт в text.
# Пайп принудительно в цвете текста (@text), чтобы CSS-классы модуля
# (например, розовый у активного tor) красили только саму иконку.
# Хвостовой пробел — запас под overdraw иконок Nerd Font: глиф рисуется
# шире своей метрической ширины, и без запаса GTK обрезает его край
"$@" | jq -c 'if (.text // "") == "" then .
    else .text = "<span color=\"#cdd6f4\"> |</span> " + .text + " " end'
